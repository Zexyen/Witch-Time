//! The `tables` step: every generated input of the runtime, read from YOUR main and sdk into runtime/gen/ (byte for byte
//! what the former runtime/gen/make_gen.py wrote; tests::stand_ins pins them). The dump-independent test vectors are
//! committed in runtime/gen_static/ and copied.

use crate::nso;
use crate::sdklift;
use crate::util::{cstr, sext, u16_at, u32_at, u64_at};
use std::collections::HashMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// copied from runtime/gen_static/ into runtime/gen/
const STATIC: [&str; 2] = ["fake_whitelist.h", "fake_openlist.h"];

struct Elf {
    b: Vec<u8>,
    /// PT_LOAD: (file offset, vaddr, file size, memory size)
    loads: Vec<(u64, u64, u64, u64)>,
    tags: HashMap<i64, u64>,
}

fn elf_layout(b: Vec<u8>) -> Elf {
    let phoff = u64_at(&b, 0x20) as usize;
    let (phentsize, phnum) = (u16_at(&b, 0x36) as usize, u16_at(&b, 0x38) as usize);
    let (mut loads, mut dynv) = (Vec::new(), None);
    for i in 0..phnum {
        let p = phoff + i * phentsize;
        let t = u32_at(&b, p);
        let (off, va, fsz, msz) = (u64_at(&b, p + 8), u64_at(&b, p + 16), u64_at(&b, p + 32), u64_at(&b, p + 40));
        if t == 1 {
            loads.push((off, va, fsz, msz));
        } else if t == 2 {
            dynv = Some(off as usize);
        }
    }
    let mut tags = HashMap::new();
    if let Some(mut d) = dynv {
        loop {
            let tag = u64_at(&b, d) as i64;
            if tag == 0 {
                break;
            }
            tags.entry(tag).or_insert(u64_at(&b, d + 8));
            d += 16;
        }
    }
    Elf { b, loads, tags }
}

fn page(x: u64) -> u64 {
    (x + 0xfff) & !0xfff
}

/// .dynsym entries between DT_SYMTAB and DT_STRTAB: (name, shndx, value)
fn dynsyms(e: &Elf) -> Result<Vec<(String, u16, u64)>, String> {
    let tag = |t: i64| e.tags.get(&t).copied().ok_or(format!("main.elf: DYNAMIC has no tag {}", t));
    let (sym, strt) = (tag(6)? as usize, tag(5)? as usize);
    let mut out = Vec::new();
    for i in 0..(strt - sym) / 24 {
        let o = 0x1000 + sym + i * 24;
        let (no, sh, val) = (u32_at(&e.b, o) as usize, u16_at(&e.b, o + 6), u64_at(&e.b, o + 8));
        if no != 0 {
            out.push((cstr(&e.b, 0x1000 + strt + no), sh, val));
        }
    }
    Ok(out)
}

pub fn run(root: &Path, log: &mut dyn FnMut(String)) -> Result<(), String> {
    let gen = root.join("runtime").join("gen");
    let exefs = root.join("targets").join("exefs");
    let rd = |p: &Path| fs::read(p).map_err(|e| format!("{}: {}", p.display(), e));
    let wr = |name: &str, s: &[u8]| fs::write(gen.join(name), s).map_err(|e| format!("{}: {}", name, e));
    // a release (git archive) or a fresh checkout has no runtime/gen/: nothing in it is tracked
    fs::create_dir_all(&gen).map_err(|e| format!("{}: {}", gen.display(), e))?;
    // sdk.elf beside main.elf, where sdklift_rt.c looks for it at run time
    let sdk_elf = exefs.join("sdk.elf");
    let c = nso::nso2elf(&rd(&exefs.join("sdk"))?)?;
    for l in c.report {
        log(l);
    }
    fs::write(&sdk_elf, &c.elf).map_err(|e| format!("{}: {}", sdk_elf.display(), e))?;
    log(format!("wrote {} {}", sdk_elf.display(), c.elf.len()));

    let m = elf_layout(rd(&exefs.join("main.elf"))?);
    let s = elf_layout(c.elf);
    let mt = |t: i64| m.tags.get(&t).copied().ok_or(format!("main.elf: DYNAMIC has no tag {}", t));
    let mut layout: Vec<(&str, u64)> = vec![
        ("FILE_IMAGE", m.loads.iter().map(|l| l.0 + l.2).max().unwrap_or(0) - 0x1000),
        ("IMAGE_SIZE", page(m.loads.iter().map(|l| l.1 + l.3).max().unwrap_or(0))),
        ("GUEST_RO_END", m.loads.iter().map(|l| l.1).max().unwrap_or(0)),
        ("RELA", mt(7)?),
        ("RELASZ", mt(8)?),
        ("JMPREL", mt(23)?),
        ("PLTRELSZ", mt(2)?),
        ("MAIN_SYMTAB", mt(6)?),
        ("MAIN_STRTAB", mt(5)?),
        ("INIT_ARRAY_OFF", mt(25)?),
        ("INIT_ARRAY_SIZE", mt(27)?),
        ("DT_INIT_OFF", mt(12)?),
        ("SDK_IMAGE_SPAN", page(s.loads.iter().map(|l| l.1 + l.3).max().unwrap_or(0))),
    ];
    let msyms = dynsyms(&m)?;
    let exports: HashMap<&str, u64> = msyms.iter().filter(|x| x.1 != 0).map(|x| (x.0.as_str(), x.2)).collect();
    for (macro_, name) in [
        ("NNINIT_STARTUP_OFF", "nninitStartup"),
        ("NN_MAIN_OFF", "nnMain"),
        ("GAME_ALIGNED_ALLOC_OFF", "aligned_alloc"),
        ("GAME_FREE_OFF", "free"),
        ("GAME_OPDELETE_OFF", "_ZdlPv"),
    ] {
        layout.push((macro_, *exports.get(name).ok_or(format!("main.elf exports no {}", name))?));
    }
    let mut h = String::from(
        "/* generated by runtime/gen/make_gen.py from targets/exefs/main.elf and sdk.elf -- do not edit.\n \
         * [Recomps#1] replaces the SSBU 13.0.4 constants hostrt.c and boot.c had hard-coded. */\n\
         #ifndef IMAGE_LAYOUT_H\n#define IMAGE_LAYOUT_H\n",
    );
    for (k, v) in &layout {
        writeln!(h, "#define {:<16} 0x{:x}ULL", k, v).unwrap();
    }
    h += "#endif\n";
    wr("image_layout.h", h.as_bytes())?;
    log(format!(
        "image_layout.h: {}",
        layout.iter().map(|(k, v)| format!("{}=0x{:x}", k, v)).collect::<Vec<_>>().join(", ")
    ));

    // imports_all.txt: undefined dynsym of main.elf
    let imports: Vec<&str> = msyms.iter().filter(|x| x.1 == 0).map(|x| x.0.as_str()).collect();
    wr("imports_all.txt", (imports.join("\n") + "\n").as_bytes())?;

    // sdkdata.c: values of the nn::util / nn::hid data symbols main imports from the sdk
    let d = &s.b;
    let shoff = u64_at(d, 0x28) as usize;
    let (shnum, shstrndx) = (u16_at(d, 0x3c) as usize, u16_at(d, 0x3e) as usize);
    let sh = |i: usize| {
        (
            u32_at(d, shoff + i * 64) as usize,
            u64_at(d, shoff + i * 64 + 24) as usize,
            u64_at(d, shoff + i * 64 + 32) as usize,
        )
    };
    let shstr = sh(shstrndx).1;
    let by_name: HashMap<String, (usize, usize)> = (0..shnum).map(|i| (cstr(d, shstr + sh(i).0), (sh(i).1, sh(i).2))).collect();
    let (sym_off, sym_size) = by_name[".dynsym"];
    let str_off = by_name[".dynstr"].0;
    let mut syms: HashMap<String, (usize, usize)> = HashMap::new();
    for i in 0..sym_size / 24 {
        let o = sym_off + i * 24;
        let name = cstr(d, str_off + u32_at(d, o) as usize);
        if u16_at(d, o + 6) != 0 && d[o + 4] & 0xf == 1 {
            syms.insert(name, (u64_at(d, o + 8) as usize, u64_at(d, o + 16) as usize));
        }
    }
    let found: Vec<(&str, &[u8])> = imports
        .iter()
        .filter(|n| n.starts_with("_ZN2nn4util") || n.starts_with("_ZN2nn3hid6NpadId"))
        .filter_map(|n| {
            syms.get(*n)
                .filter(|v| 0 < v.1 && v.1 <= 1 << 20)
                .map(|v| (*n, &d[0x1000 + v.0..0x1000 + v.0 + v.1]))
        })
        .collect();
    let mut f = String::from("/* generated by runtime/gen/make_gen.py from our sdk module -- do not edit */\n#include \"hostrt.h\"\n\n");
    for (k, (_, data)) in found.iter().enumerate() {
        writeln!(
            f,
            "static const unsigned char d{}[] = {{{}}};",
            k,
            data.iter().map(|b| b.to_string()).collect::<Vec<_>>().join(",")
        )
        .unwrap();
    }
    f += "\nconst SdkData sdk_data[] = {\n";
    for (k, (name, data)) in found.iter().enumerate() {
        writeln!(f, "  {{ \"{}\", d{}, {} }},", name, k, data.len()).unwrap();
    }
    if found.is_empty() {
        f += "  { 0, 0, 0 },\n";
    }
    writeln!(f, "}};\nconst int sdk_data_count = {};", found.len()).unwrap();
    wr("sdkdata.c", f.as_bytes())?;
    log(format!("sdkdata.c: {} data symbols from our sdk", found.len()));

    // nvn_devinfo.h: nvnDeviceGetInteger's fixed answers, read from the sdk's own NVN code
    let (devinfo, note) = Sdk {
        d,
        text: s.loads.first().map(|l| l.2 as i64).unwrap_or(0),
    }
    .devinfo()?;
    if let Some(n) = note {
        log(n);
    }
    let devinfo = if devinfo.is_empty() { vec![-1] } else { devinfo };
    let mut f = String::from(
        "/* generated by runtime/gen/make_gen.py from YOUR sdk (targets/exefs/sdk.elf) -- do not edit, never publish.\n \
         * nvnDeviceGetInteger's fixed answers in the sdk's own NVN code, by pname; -1 = the sdk answers from the live\n \
         * device state (runtime/nvn_stub.c then has the value). */\n",
    );
    writeln!(
        f,
        "#define NVN_DEVINFO_SDK_COUNT {}\nstatic const int nvn_devinfo_sdk[NVN_DEVINFO_SDK_COUNT] = {{",
        devinfo.len()
    )
    .unwrap();
    for ch in devinfo.chunks(8) {
        writeln!(f, "    {}", ch.iter().map(|v| format!("{},", v)).collect::<Vec<_>>().join(" ")).unwrap();
    }
    f += "};\n";
    wr("nvn_devinfo.h", f.as_bytes())?;
    log(format!(
        "nvn_devinfo.h: {} of {} nvnDeviceGetInteger answers are fixed numbers in our sdk",
        devinfo.iter().filter(|v| **v >= 0).count(),
        devinfo.len()
    ));

    // the dump-independent vectors (quad, eh, sdktest, audit lists)
    let st = root.join("runtime").join("gen_static");
    for n in STATIC {
        wr(n, &rd(&st.join(n))?)?;
    }
    // sdklift_install.h, then the SDK lift
    wr("sdklift_install.h", &install_header(root)?)?;
    sdklift::gen(&sdk_elf, &root.join("lifter").join("sdklift_roots.txt"), &gen, log)?;
    log(format!("generated inputs written to {}", gen.display()));
    Ok(())
}

// ---- nvn_devinfo: the switch over the pname in nvnDeviceGetInteger and its getter

const NVN_GETINT_ENTRY: i64 = 0x2bfe0c;
const NVN_GETINT: i64 = 0x2c0f30;
/// ldur w0, [x29, #-4]
const LDUR_W0: u32 = 0xb85fc3a0;

struct Sdk<'a> {
    d: &'a [u8],
    text: i64,
}

/// (bl target, bias, bound, table, default target) of a B2-style switch
type A64Switch = (i64, i64, i64, i64, Option<i64>);
/// (bound, bias, table, base, preset w0) of an adr/ldrb jump table
type BSwitch = (i64, i64, i64, i64, Option<(i128, u32)>);

fn bitmask32(immr: u32, imms: u32) -> Option<i128> {
    for size in [2u32, 4, 8, 16, 32] {
        if size == 32 || (imms & !(size - 1) & 0x3f) == (0x3f & !(2 * size - 1)) {
            let ones = (imms & (size - 1)) + 1;
            if ones == size {
                return None;
            }
            let (r, pat) = (immr & (size - 1), (1u64 << ones) - 1);
            let pat = ((pat >> r) | (pat << (size - r))) & ((1u64 << size) - 1);
            return Some((0..32).step_by(size as usize).map(|k| (pat as i128) << k).sum());
        }
    }
    None
}

/// "mov wD, #imm" as movz or as orr wD, wzr, #bitmask: (imm, D)
fn mov_imm(w: u32) -> Option<(i128, u32)> {
    if w & 0xff800000 == 0x52800000 {
        return Some(((((w >> 5) & 0xffff) as i128) << (16 * ((w >> 21) & 3)), w & 31));
    }
    if w & 0xffc003e0 == 0x320003e0 {
        return bitmask32((w >> 16) & 0x3f, (w >> 10) & 0x3f).map(|v| (v, w & 31));
    }
    None
}

fn adrp_page(va: i64, w: u32) -> i64 {
    (va & !0xfff) + (sext((((w >> 29) & 3) | (((w >> 5) & 0x7ffff) << 2)) as i64, 21) << 12)
}

impl Sdk<'_> {
    fn ins(&self, va: i64) -> Result<u32, String> {
        let o = 0x1000 + va;
        if o < 0 || o as usize + 4 > self.d.len() {
            return Err(format!("nvn_devinfo: sdk 0x{:x} is outside the sdk", va));
        }
        Ok(u32_at(self.d, o as usize))
    }

    fn a64_switch(&self, fn_: i64) -> Result<A64Switch, String> {
        let (mut bl, mut bias, mut bound, mut page, mut table, mut dflt) = (0, None, None, None, None, None);
        for va in (fn_..fn_ + 0x80).step_by(4) {
            let w = self.ins(va)?;
            if w >> 26 == 0x25 {
                bl = va + 4 * sext((w & 0x3ffffff) as i64, 26);
            } else if w & 0xffc00000 == 0x51000000 {
                bias = Some(((w >> 10) & 0xfff) as i64);
            } else if w & 0xffc0001f == 0x7100001f {
                bound = Some(((w >> 10) & 0xfff) as i64);
            } else if w & 0xff00001f == 0x54000008 {
                dflt = Some(va + 4 * sext(((w >> 5) & 0x7ffff) as i64, 19));
            } else if w & 0x9f000000 == 0x90000000 {
                page = Some(adrp_page(va, w));
            } else if w & 0xffc00000 == 0x91000000 && page.is_some() && table.is_none() {
                table = Some(page.unwrap() + ((w >> 10) & 0xfff) as i64);
            } else if w & 0xfffffc1f == 0xd61f0000 {
                if let (Some(bound), Some(table)) = (bound, table) {
                    return Ok((bl, bias.unwrap_or(0), bound, table, dflt));
                }
                break;
            }
        }
        Err(format!("nvn_devinfo: no switch at sdk 0x{:x}: not the sdk this port supports", fn_))
    }

    fn case_target(&self, sw: &A64Switch, p: i64) -> Result<i64, String> {
        let (_, bias, bound, table, dflt) = *sw;
        let i = p - bias;
        if i < 0 || i > bound {
            return dflt.ok_or_else(|| "nvn_devinfo: switch without a default".to_string());
        }
        Ok(table + self.ins(table + 4 * i)? as i32 as i64)
    }

    fn b_switch(&self, br: i64) -> Result<Option<BSwitch>, String> {
        let (mut bias, mut bound, mut page, mut table, mut base, mut preset) = (None, None, None, None, None, None);
        for va in (br - 48..br).step_by(4) {
            let w = self.ins(va)?;
            if w & 0xffc00000 == 0x51000000 {
                bias = Some(((w >> 10) & 0xfff) as i64);
            } else if w & 0xffc0001f == 0x7100001f {
                bound = Some(((w >> 10) & 0xfff) as i64);
            } else if w & 0x9f000000 == 0x90000000 {
                page = Some(adrp_page(va, w));
            } else if w & 0xffc00000 == 0x91000000 && page.is_some() {
                table = Some(page.unwrap() + ((w >> 10) & 0xfff) as i64);
            } else if w & 0x9f000000 == 0x10000000 {
                base = Some(va + sext(((((w >> 5) & 0x7ffff) << 2) | ((w >> 29) & 3)) as i64, 21));
            } else if let Some(m) = mov_imm(w) {
                preset = Some(m);
            }
        }
        let mut ldrb = false;
        for k in (4..20).step_by(4) {
            ldrb |= self.ins(br - k)? & 0xffe0fc00 == 0x38606800;
        }
        Ok(match (bound, table, base) {
            (Some(bound), Some(table), Some(base)) if ldrb => Some((bound, bias.unwrap_or(0), table, base, preset)),
            _ => None,
        })
    }

    fn b_case(&self, sw: &BSwitch, p: i64) -> Result<Option<i64>, String> {
        let (bound, bias, table, base, _) = *sw;
        if !(0 <= p - bias && p - bias <= bound) {
            return Ok(None);
        }
        let o = (0x1000 + table + p - bias) as usize;
        let b = *self.d.get(o).ok_or("nvn_devinfo: jump table outside the sdk")?;
        Ok(Some(base + 4 * b as i64))
    }

    fn find_b3_getint(&self) -> Result<Option<(BSwitch, Vec<i64>)>, String> {
        for br in (0..self.text).step_by(4) {
            if self.ins(br)? & 0xfffffc1f != 0xd61f0000 {
                continue;
            }
            let Some(sw) = self.b_switch(br)? else { continue };
            if sw.0 < 0x40 {
                continue;
            }
            let mut all = true;
            for (p, v) in [(4, 256i128), (0xf, 32), (0x24, 1 << 20), (0x25, 4096)] {
                let ok = match self.b_case(&sw, p)? {
                    Some(c) => mov_imm(self.ins(c)?).is_some_and(|m| m.0 == v),
                    None => false,
                };
                if !ok {
                    all = false;
                    break;
                }
            }
            if !all {
                continue;
            }
            // the function's entry: the nearest BL target at or before the switch
            let mut bls: HashMap<i64, Vec<i64>> = HashMap::new();
            for va in (0..self.text).step_by(4) {
                let w = self.ins(va)?;
                if w >> 26 == 0x25 {
                    bls.entry(va + 4 * sext((w & 0x3ffffff) as i64, 26)).or_default().push(va);
                }
            }
            let fn_ = bls
                .keys()
                .filter(|&&t| br - 0x100 < t && t <= br)
                .max()
                .copied()
                .ok_or("nvn_devinfo: the getter has no caller")?;
            return Ok(Some((sw, bls.remove(&fn_).unwrap())));
        }
        Ok(None)
    }

    /// nvnDeviceGetInteger's answer for every pname (-1 = from the live device), and the line the step prints
    fn devinfo(&self) -> Result<(Vec<i128>, Option<String>), String> {
        let mut out = Vec::new();
        let mut note = None;
        let call = 0x94000000u32 | (((NVN_GETINT - NVN_GETINT_ENTRY - 0x1c) / 4) as u32 & 0x3ffffff);
        let (outer, inner);
        if self.ins(NVN_GETINT_ENTRY + 0x1c)? == call {
            outer = self.a64_switch(NVN_GETINT)?; // B2's sdk (SDK 3.6.0)
            inner = self.a64_switch(outer.0)?;
        } else {
            outer = (0, 0, -1, 0, Some(0));
            inner = outer;
            match self.find_b3_getint()? {
                Some((getter, callers)) if callers.len() == 1 => {
                    let find = |from: i64, to: i64, pred: &dyn Fn(u32) -> bool| -> Result<i64, String> {
                        for va in (from..to).step_by(4) {
                            if pred(self.ins(va)?) {
                                return Ok(va);
                            }
                        }
                        Err("nvn_devinfo: nvnDeviceGetInteger's switch has an unexpected shape".into())
                    };
                    let br = find(callers[0], callers[0] + 0x80, &|w| w & 0xfffffc1f == 0xd61f0000)?;
                    let osw = self.b_switch(br)?.ok_or("nvn_devinfo: nvnDeviceGetInteger has no jump table")?;
                    let ret = find(br + 4, br + 0x40, &|w| w == 0xd65f03c0)?;
                    let epilogue = ret - 12; // the shared return: ldp, ldp, add sp, ret
                    for p in 0..=(osw.1 + osw.0).max(getter.1 + getter.0) {
                        let t = self.b_case(&osw, p)?;
                        let w = match t {
                            Some(t) => self.ins(t)?,
                            None => LDUR_W0, // past the bound: the getter's answer
                        };
                        let m = mov_imm(w);
                        let v = if t.is_some_and(|t| epilogue <= t && t <= ret) {
                            match osw.4 {
                                Some((imm, 0)) if t == Some(epilogue) => imm,
                                _ => -1,
                            }
                        } else if let Some((imm, 0)) = m {
                            imm
                        } else if w == LDUR_W0 {
                            let gm = match self.b_case(&getter, p)? {
                                Some(g) => mov_imm(self.ins(g)?),
                                None => None,
                            };
                            match (gm, getter.4) {
                                (Some((_, 0)), Some((imm, 8))) => imm, // the getter's shared tail: "*out = w8", w8 preset
                                (Some((imm, 8)), _) => imm,
                                _ => 0,
                            }
                        } else {
                            -1
                        };
                        out.push(v);
                    }
                    note = Some(format!(
                        "nvn_devinfo: getter switch and nvnDeviceGetInteger (caller sdk 0x{:x}) found by their constants",
                        callers[0]
                    ));
                }
                _ => note = Some("nvn_devinfo: nvnDeviceGetInteger not found in this sdk: no fixed answers taken".into()),
            }
        }
        for p in 0..=(inner.1 + inner.2) {
            let t = self.case_target(&outer, p)?;
            let w = self.ins(t)?;
            let v = if let Some((imm, 0)) = mov_imm(w) {
                imm
            } else if w & 0xffc003ff == 0xb94003e0 {
                // ldr w0, [sp, #..]: what the getter stored (0 = not answered)
                let i = p - inner.1;
                if i < 0 || i > inner.2 {
                    0
                } else {
                    let w2 = self.ins(self.case_target(&inner, p)?)?;
                    match mov_imm(w2) {
                        Some((imm, _)) => imm,
                        None if w2 == 0xd65f03c0 => 0,
                        None => -1,
                    }
                }
            } else {
                -1
            };
            out.push(v);
        }
        Ok((out, note))
    }
}

/// runtime/gen/sdklift_install.h from lifter/sdklift_install.txt (no dump needed: the prebuilt runtime has it too)
pub fn install_header(root: &Path) -> Result<Vec<u8>, String> {
    let txt = fs::read(root.join("lifter").join("sdklift_install.txt")).map_err(|e| format!("sdklift_install.txt: {}", e))?;
    let txt = String::from_utf8_lossy(&txt);
    let install: Vec<&str> = txt.lines().filter(|l| !l.trim().is_empty() && !l.starts_with('#')).map(str::trim).collect();
    let mut f = String::from(
        "/* generated by runtime/gen/make_gen.py from lifter/sdklift_install.txt: imports whose host handler is replaced by\n \
         * the lifted SDK code (installed by nnsdk2.c) */\nstatic const char *const sdk_install_names[] = {\n",
    );
    for n in &install {
        writeln!(f, "    \"{}\",", n).unwrap();
    }
    if install.is_empty() {
        f += "    \"\",\n";
    }
    f += "};\n";
    Ok(f.into_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::golden;

    /// what runtime/gen gets from the dump (and sdklift_install.txt), checked against testdata/golden/tables
    const GOLDEN: [&str; 8] = [
        "image_layout.h",
        "imports_all.txt",
        "sdkdata.c",
        "nvn_devinfo.h",
        "sdklift_install.h",
        "sdklift_gen.c",
        "nvn_sdk_addrs.h",
        "sdklift_report.txt",
    ];

    /// the step on the committed stand-in main and sdk (testdata/fake_main), in a temporary tree with no runtime/gen/
    #[test]
    fn stand_ins() {
        let here = Path::new(env!("CARGO_MANIFEST_DIR"));
        let (repo, fake) = (here.join("../.."), here.join("testdata/fake_main"));
        let st = repo.join("runtime/gen_static");
        let t = std::env::temp_dir().join(format!("wtbuild-tables-{}", std::process::id()));
        let _ = fs::remove_dir_all(&t);
        let put = |rel: &str, b: &[u8]| {
            let p = t.join(rel);
            fs::create_dir_all(p.parent().unwrap()).unwrap();
            fs::write(p, b).unwrap();
        };
        put("targets/exefs/main.elf", &nso::nso2elf(&fs::read(fake.join("main.nso")).unwrap()).unwrap().elf);
        put("targets/exefs/sdk", &fs::read(fake.join("sdk.nso")).unwrap());
        put("lifter/sdklift_install.txt", &fs::read(repo.join("lifter/sdklift_install.txt")).unwrap());
        put("lifter/sdklift_roots.txt", &fs::read(fake.join("roots.txt")).unwrap());
        for n in STATIC {
            put(&format!("runtime/gen_static/{}", n), &fs::read(st.join(n)).unwrap());
        }

        let (root, mut log) = (t.display().to_string(), String::new());
        run(&t, &mut |l| log += &format!("{}\n", l.replace(&root, "<tmp>").replace('\\', "/"))).unwrap();
        golden::check("tables/log.txt", &log);
        let gen = t.join("runtime/gen");
        for n in GOLDEN {
            golden::check(&format!("tables/{}", n), &fs::read_to_string(gen.join(n)).unwrap());
        }
        for n in STATIC {
            assert!(
                fs::read(gen.join(n)).unwrap() == fs::read(st.join(n)).unwrap(),
                "{} differs from runtime/gen_static's",
                n
            );
        }
        let mut names: Vec<String> = fs::read_dir(&gen)
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        let mut want: Vec<&str> = GOLDEN.iter().chain(&STATIC).copied().collect();
        names.sort();
        want.sort();
        assert_eq!(names, want);
        let sdk_elf = crate::util::sha256_file(&t.join("targets/exefs/sdk.elf")).unwrap();
        golden::check("tables/sdk.elf.sha256", &format!("{}\n", sdk_elf));
        fs::remove_dir_all(&t).unwrap();
    }
}
