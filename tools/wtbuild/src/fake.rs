//! Stand-in modules with no game code (testdata/fake_main): generated C functions, fake.cpp and the extras, compiled for
//! AArch64 with clang and linked by ld.lld into the NSO layout (MOD0 first, text / rodata / data at their offsets), then
//! packed as an NSO with every segment LZ4-compressed.
//!
//!     wtbuild fake-nso <out.nso> [functions=300] [--seed N=1] [--extra <file.c|.s>]... [--ld <flag>]... [--repo <dir>]
//!
//! The golden tests read the two committed stand-ins, made (clang and ld.lld 23.1.4) from the checkout with
//!
//!     F=tools/wtbuild/testdata/fake_main
//!     tools/wtbuild/target/release/wtbuild fake-nso $F/main.nso 400 --seed 1 --extra $F/tables_main.c --ld -init=nninitStartup
//!     tools/wtbuild/target/release/wtbuild fake-nso $F/sdk.nso 300 --seed 2 --extra $F/tables_sdk.c --extra $F/fake_nvn.s \
//!         --extra $F/fake_nvn_procs.s --ld --no-relax
//!
//! Another clang makes other code, so regenerating them means re-blessing the goldens (WTBUILD_BLESS=1 cargo test --release).

use crate::compile;
use crate::target;
use crate::util::{u16_at, u32_at, u64_at};
use sha2::{Digest, Sha256};
use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// splitmix64
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e3779b97f4a7c15);
        let z = (self.0 ^ (self.0 >> 30)).wrapping_mul(0xbf58476d1ce4e5b9);
        let z = (z ^ (z >> 27)).wrapping_mul(0x94d049bb133111eb);
        z ^ (z >> 31)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
    fn range(&mut self, lo: usize, hi: usize) -> usize {
        lo + self.below(hi - lo)
    }
    fn unit(&mut self) -> f64 {
        (self.next() >> 11) as f64 / (1u64 << 53) as f64
    }
}

/// n functions with switches, loops, float and integer math, calls between them and to imports
fn gen_c(n: usize, r: &mut Rng) -> String {
    let mut out = String::from(
        "/* generated by wtbuild fake-nso */\nvoid ext_log(int); int ext_value(void); float ext_scale(float);\n\
         typedef unsigned long u64; typedef long i64; typedef unsigned u32;\n",
    );
    for i in 0..n {
        writeln!(out, "i64 g{}(i64 a, u64 b, double d, float f);", i).unwrap();
    }
    for i in 0..n {
        let mut body = Vec::new();
        match r.below(6) {
            0 => {
                let cases: Vec<String> = (0..r.range(5, 12))
                    .map(|c| {
                        let (m, s) = (r.range(3, 99), r.range(1, 40));
                        let log = if r.unit() < 0.5 { format!("ext_log({});", c) } else { String::new() };
                        format!("case {}: a = a * {} + (i64)(b >> {}); {} break;", c, m, s, log)
                    })
                    .collect();
                body.push(format!(
                    "switch ((int)(b & 15)) {{ {} default: a ^= 0x{:x}; }}",
                    cases.join(" "),
                    r.next() >> 33
                ));
            }
            1 => body.push(format!(
                "for (int i = 0; i < (int)(b & 63); i++) {{ d = d * {:?} + f; f = f * 0.5f + (float)i; a += (i64)d; }}",
                r.unit() + 0.5
            )),
            2 => body.push(format!(
                "u64 r = b; for (int i = 0; i < 8; i++) r = (r << {}) ^ (r >> {}) ^ (u64)a * 0x{:x}UL; a = (i64)r;",
                r.range(1, 20),
                r.range(1, 20),
                r.next() >> 16 | 1
            )),
            3 => body.push(format!(
                "float v[8]; for (int i = 0; i < 8; i++) v[i] = f * (float)i + ext_scale((float)a); \
                 for (int i = 0; i < 8; i++) d += v[i] * v[(i + 3) & 7]; a = (i64)(d * {:?});",
                r.unit()
            )),
            4 => body.push(format!(
                "if (a < 0) return (i64)__builtin_sqrt(d < 0 ? -d : d) + (i64)(b % {}); a = a / (i64)((b & 7) + 1) - (i64)(u32)b;",
                r.range(3, 1000)
            )),
            _ => body.push("a += ext_value(); b ^= (u64)a << 3; d += (double)(u32)b / 7.0;".into()),
        }
        for _ in 0..r.below(3) {
            let j = r.below(n);
            body.push(if j > i {
                format!("a += g{}(a ^ {}, b + {}, d * 0.75, f - 1.0f);", j, r.below(100), r.below(100))
            } else {
                format!("a -= (i64)b >> {};", r.range(1, 9))
            });
        }
        writeln!(
            out,
            "i64 g{}(i64 a, u64 b, double d, float f) {{ {} return a + (i64)d + (i64)f; }}",
            i,
            body.join(" ")
        )
        .unwrap();
    }
    let table: Vec<String> = (0..n).step_by(3).map(|i| format!("g{}", i)).collect();
    writeln!(out, "i64 (*const gtable[])(i64, u64, double, float) = {{{}}};", table.join(", ")).unwrap();
    out
}

/// the NSO of an ELF whose PT_LOADs are text (at 0), rodata and data: every segment LZ4-compressed (flags 7), the build ID
/// the first 20 bytes of the segments' SHA-256. Also the three segment sizes.
pub fn elf2nso(elf: &[u8]) -> Result<(Vec<u8>, [usize; 3]), String> {
    if elf.len() < 0x40 || &elf[..4] != b"\x7fELF" {
        return Err("not an ELF file".into());
    }
    let (phoff, phnum) = (u64_at(elf, 0x20) as usize, u16_at(elf, 0x38) as usize);
    let mut loads = Vec::new();
    for i in 0..phnum {
        let p = phoff + i * 0x38;
        let ph = elf.get(p..p + 0x38).ok_or("program headers past the end of the file")?;
        if u32_at(ph, 0) == 1 {
            let (off, fsz) = (u64_at(ph, 8) as usize, u64_at(ph, 32) as usize);
            let seg = elf.get(off..off + fsz).ok_or("a segment past the end of the file")?;
            loads.push((u64_at(ph, 16) as u32, seg.to_vec(), u64_at(ph, 40) as usize));
        }
    }
    if loads.len() != 3 || loads[0].0 != 0 {
        return Err("expected text, rodata, data".into());
    }
    let n = loads[0].1.len().next_multiple_of(4);
    loads[0].1.resize(n, 0);
    let mut hdr = vec![0u8; 0x100];
    hdr[..4].copy_from_slice(b"NSO0");
    hdr[12..16].copy_from_slice(&7u32.to_le_bytes());
    let mut blobs = Vec::new();
    let mut pos = 0x100;
    for (i, (va, seg, _)) in loads.iter().enumerate() {
        let stored = lz4_flex::block::compress(seg);
        for (k, v) in [pos as u32, *va, seg.len() as u32].into_iter().enumerate() {
            hdr[0x10 + 0x10 * i + 4 * k..][..4].copy_from_slice(&v.to_le_bytes());
        }
        hdr[0x60 + 4 * i..][..4].copy_from_slice(&(stored.len() as u32).to_le_bytes());
        hdr[0xA0 + 0x20 * i..][..0x20].copy_from_slice(&Sha256::digest(seg));
        pos += stored.len();
        blobs.extend(stored);
    }
    let bss = loads[2].2 - loads[2].1.len();
    hdr[0x3c..0x40].copy_from_slice(&(bss as u32).to_le_bytes());
    let mut h = Sha256::new();
    for (_, seg, _) in &loads {
        h.update(seg);
    }
    hdr[0x40..0x54].copy_from_slice(&h.finalize()[..20]);
    hdr.extend(blobs);
    Ok((hdr, [loads[0].1.len(), loads[1].1.len(), loads[2].1.len()]))
}

/// builds the stand-in from `dir`'s fake.cpp, mod0.s and link.ld, with `clang` and the ld.lld beside it
pub fn build(dir: &Path, clang: &str, out: &Path, nfuncs: usize, seed: u64, extra: &[PathBuf], ldflags: &[String]) -> Result<String, String> {
    let t = std::env::temp_dir().join(format!("wtfake_{}", std::process::id()));
    let r = (|| -> Result<Vec<u8>, String> {
        fs::create_dir_all(&t).map_err(|e| format!("{}: {}", t.display(), e))?;
        fs::write(t.join("gen.c"), gen_c(nfuncs, &mut Rng(seed))).map_err(|e| e.to_string())?;
        let sh = |c: &mut Command| {
            let (code, o, _) = compile::run(c, None);
            if code == Some(0) {
                Ok(())
            } else {
                Err(format!("{} failed:\n{}", c.get_program().to_string_lossy(), compile::tail(&o, 3000)))
            }
        };
        let tgt = ["--target=aarch64-linux-gnu", "-fPIC", "-nostdinc", "-nostdlib", "-fno-builtin"];
        let mut objs = Vec::new();
        for (i, x) in extra.iter().enumerate() {
            objs.push(t.join(format!("extra{}.o", i)));
            sh(Command::new(clang).args(tgt).args(["-O2", "-c"]).arg(x).arg("-o").arg(&objs[i]))?;
        }
        sh(Command::new(clang)
            .args(tgt)
            .args(["-O2", "-fexceptions", "-c"])
            .arg(dir.join("fake.cpp"))
            .arg("-o")
            .arg(t.join("fake.o")))?;
        sh(Command::new(clang)
            .args(tgt)
            .args(["-O2", "-c"])
            .arg(t.join("gen.c"))
            .arg("-o")
            .arg(t.join("gen.o")))?;
        sh(Command::new(clang).args(tgt).arg("-c").arg(dir.join("mod0.s")).arg("-o").arg(t.join("mod0.o")))?;
        // mod0.o first: MOD0 at the start of text
        let lld = Path::new(clang).with_file_name(target::exe("ld.lld"));
        sh(Command::new(lld)
            .args(["-shared", "--hash-style=sysv", "-T"])
            .arg(dir.join("link.ld"))
            .args(["-z", "norelro", "--eh-frame-hdr"])
            .args([t.join("mod0.o"), t.join("fake.o"), t.join("gen.o")])
            .args(&objs)
            .args(ldflags)
            .arg("-o")
            .arg(t.join("fake.so")))?;
        fs::read(t.join("fake.so")).map_err(|e| e.to_string())
    })();
    let _ = fs::remove_dir_all(&t);
    let (nso, n) = elf2nso(&r?)?;
    fs::write(out, nso).map_err(|e| format!("{}: {}", out.display(), e))?;
    Ok(format!("{}: text {}, rodata {}, data {} bytes", out.display(), n[0], n[1], n[2]))
}

/// (out, functions, seed, extras, linker flags); --seed, --extra, --ld and --repo take the next argument as it is
fn parse(args: &[String]) -> Result<(PathBuf, usize, u64, Vec<PathBuf>, Vec<String>), String> {
    let (mut pos, mut seed, mut extra, mut ld) = (Vec::new(), 1, Vec::new(), Vec::new());
    let mut it = args.iter();
    while let Some(a) = it.next() {
        if matches!(a.as_str(), "--seed" | "--extra" | "--ld" | "--repo") {
            let v = it.next().ok_or(format!("{} needs a value", a))?;
            match a.as_str() {
                "--seed" => seed = v.parse().map_err(|_| format!("--seed {}: a number", v))?,
                "--extra" => extra.push(PathBuf::from(v)),
                "--ld" => ld.push(v.clone()),
                _ => {}
            }
        } else {
            pos.push(a);
        }
    }
    let n = match pos.get(1) {
        Some(n) => n.parse().map_err(|_| format!("{}: a number of functions", n))?,
        None => 300,
    };
    match pos.len() {
        1 | 2 => Ok((PathBuf::from(pos[0]), n, seed, extra, ld)),
        _ => Err("usage: fake-nso <out.nso> [functions] [--seed N] [--extra <file.c|.s>]... [--ld <flag>]...".into()),
    }
}

pub fn main(args: &[String]) -> Result<(), String> {
    let (out, n, seed, extra, ld) = parse(args)?;
    let repo = crate::repo_root(args);
    let dir = repo.join("tools").join("wtbuild").join("testdata").join("fake_main");
    println!("{}", build(&dir, &compile::find_clang(&repo), &out, n, seed, &extra, &ld)?);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn args() {
        let a: Vec<String> = "o.nso --ld --no-relax 40 --extra x.s --seed 7 --ld -init=f"
            .split(' ')
            .map(String::from)
            .collect();
        let (out, n, seed, extra, ld) = parse(&a).unwrap();
        assert_eq!((out, n, seed, extra), (PathBuf::from("o.nso"), 40, 7, vec![PathBuf::from("x.s")]));
        assert_eq!(ld, ["--no-relax", "-init=f"]);
        assert_eq!(parse(&["o".into()]).unwrap().1, 300);
        assert!(parse(&["o".into(), "--ld".into()]).is_err());
    }

    #[test]
    fn gen_c_is_seeded() {
        let a = gen_c(30, &mut Rng(1));
        assert_eq!(a, gen_c(30, &mut Rng(1)));
        assert_ne!(a, gen_c(30, &mut Rng(2)));
        assert_eq!(a.matches("i64 g").count(), 60);
        assert!(a.ends_with("= {g0, g3, g6, g9, g12, g15, g18, g21, g24, g27};\n"));
    }

    /// an ELF of 3 PT_LOADs (and a PT_DYNAMIC) -> NSO -> nso2elf gives the segments, the bss and the build ID back
    #[test]
    fn nso_round_trip() {
        let mut text = vec![0u8; 0x22]; // not a multiple of 4: padded
        text[4..8].copy_from_slice(&8u32.to_le_bytes());
        text[8..12].copy_from_slice(b"MOD0");
        for (k, v) in [0x2000 - 8, 0x2040 - 8, 0x2060 - 8].into_iter().enumerate() {
            text[12 + 4 * k..][..4].copy_from_slice(&(v as i32).to_le_bytes());
        }
        let ro: Vec<u8> = (0..0x40u8).map(|i| if i < 0x19 { 0 } else { i }).collect(); // a null symbol, then an empty dynstr
        let mut data = Vec::new();
        for (t, v) in [(6u64, 0x1000u64), (5, 0x1018), (10, 1), (0, 0)] {
            data.extend(t.to_le_bytes());
            data.extend(v.to_le_bytes());
        }
        let mut elf = vec![0u8; 0x40];
        elf[..4].copy_from_slice(b"\x7fELF");
        elf[0x20..0x28].copy_from_slice(&0x40u64.to_le_bytes());
        elf[0x38..0x3a].copy_from_slice(&4u16.to_le_bytes());
        let segs = [
            (1u32, 0x1000u64, 0u64, &text, 0x22u64),
            (2, 0x1200, 0x2000, &data, 0x40),
            (1, 0x1100, 0x1000, &ro, 0x40),
            (1, 0x1200, 0x2000, &data, 0x60),
        ];
        for (t, off, va, d, msz) in segs {
            elf.extend(t.to_le_bytes());
            elf.extend(0u32.to_le_bytes());
            for v in [off, va, va, d.len() as u64, msz, 0x1000] {
                elf.extend(v.to_le_bytes());
            }
        }
        elf.resize(0x1300, 0);
        elf[0x1000..0x1022].copy_from_slice(&text);
        elf[0x1100..0x1140].copy_from_slice(&ro);
        elf[0x1200..0x1240].copy_from_slice(&data);

        let (nso, sizes) = elf2nso(&elf).unwrap();
        assert_eq!(sizes, [0x24, 0x40, 0x40]);
        assert_eq!((u32_at(&nso, 12), u32_at(&nso, 0x3c)), (7, 0x20));
        let c = crate::nso::nso2elf(&nso).unwrap();
        assert!(c.hashes_ok);
        text.resize(0x24, 0);
        let id = Sha256::digest([&text[..], &ro, &data].concat());
        assert!(nso[0x54..0x60].iter().all(|&b| b == 0));
        assert_eq!(c.report[3], format!("build id {}", crate::util::hex(&id[..20])));
        for (va, d) in [(0, &text), (0x1000, &ro), (0x2000, &data)] {
            assert_eq!(&c.elf[0x1000 + va..][..d.len()], &d[..]);
        }
        assert_eq!(elf2nso(&elf[..0x40 + 0x38 * 2]).err().unwrap(), "a segment past the end of the file");
    }
}
