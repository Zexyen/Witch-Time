# ---- nvn_devinfo.h: nvnDeviceGetInteger's answers, read from the player's own sdk (2026-10-17). NVN's code in the sdk answers
# most parameters with a fixed number: a switch over the pname (NVN_GETINT, its jump table) whose cases are "mov w0, #imm",
# or "the getter's answer" (NVN_GETINT_TABLE: a second switch of "mov w8, #imm" cases). Those numbers are taken here, so
# the repository does not carry them (runtime/nvn_stub.c uses them first). Cases that read the live device object
# instead get -1. Addresses in the sdk this port verifies by SHA-256 (scripts/setup.py), checked below against the code.
NVN_GETINT_ENTRY, NVN_GETINT = 0x2bfe0c, 0x2c0f30       # nvnDeviceGetInteger, and the function it calls with the pname


def sdk_ins(va):
    return struct.unpack_from('<I', sb, 0x1000 + va)[0]


def sx(v, bits):
    return v - (1 << bits) if v & (1 << (bits - 1)) else v


def a64_switch(fn):
    """The bounds check and jump table of a switch function: (bl target, bias, bound, table, default target)."""
    bl = bias = bound = page_ = table = dflt = None
    for va in range(fn, fn + 0x80, 4):
        w = sdk_ins(va)
        if w >> 26 == 0x25:
            bl = va + 4 * sx(w & 0x3ffffff, 26)                                  # bl
        elif (w & 0xffc00000) == 0x51000000:
            bias = (w >> 10) & 0xfff                                             # sub wD, wN, #imm
        elif (w & 0xffc0001f) == 0x7100001f:
            bound = (w >> 10) & 0xfff                                            # cmp wN, #imm
        elif (w & 0xff00001f) == 0x54000008:
            dflt = va + 4 * sx((w >> 5) & 0x7ffff, 19)                           # b.hi
        elif (w & 0x9f000000) == 0x90000000:                                     # adrp
            page_ = (va & ~0xfff) + (sx(((w >> 29) & 3) | (((w >> 5) & 0x7ffff) << 2), 21) << 12)
        elif (w & 0xffc00000) == 0x91000000 and page_ is not None and table is None:
            table = page_ + ((w >> 10) & 0xfff)                                  # add xD, xN, #lo12
        elif (w & 0xfffffc1f) == 0xd61f0000:                                     # br
            if bound is None or table is None:
                break
            return bl, bias or 0, bound, table, dflt
    sys.exit('nvn_devinfo: no switch at sdk 0x%x: not the sdk this port supports' % fn)


def bitmask32(immr, imms):                               # AArch64 DecodeBitMasks, 32-bit, N = 0
    for size in (2, 4, 8, 16, 32):
        if size == 32 or (imms & ~(size - 1) & 0x3f) == (0x3f & ~(2 * size - 1)):
            ones = (imms & (size - 1)) + 1
            if ones == size:
                return None
            r, pat = immr & (size - 1), (1 << ones) - 1
            pat = ((pat >> r) | (pat << (size - r))) & ((1 << size) - 1)
            return sum(pat << k for k in range(0, 32, size))


def mov_imm(w):
    """'mov wD, #imm' as movz or as orr wD, wzr, #bitmask: (imm, D), else None."""
    if (w & 0xff800000) == 0x52800000:
        return ((w >> 5) & 0xffff) << (16 * ((w >> 21) & 3)), w & 31
    if (w & 0xffc003e0) == 0x320003e0:
        v = bitmask32((w >> 16) & 0x3f, (w >> 10) & 0x3f)
        return (v, w & 31) if v is not None else None
    return None


def case_target(sw, p):
    bl, bias, bound, table, dflt = sw
    i = p - bias
    return dflt if i < 0 or i > bound else table + struct.unpack_from('<i', sb, 0x1000 + table + 4 * i)[0]


# [witchtime] Bayonetta 3's sdk (NVN of nnSdk 13.3.2) has no proc-name strings and other addresses, and its switches use
# compact jump tables (adr base + ldrb entry * 4). The same two functions are found by what they are: the getter is the
# one switch of the sdk whose cases answer 256 for pname 4 (uniform buffer alignment), 32 for 0xf (texture descriptor),
# 1 << 20 for 0x24 (texture pool) and 4096 for 0x25 (sampler pool): bool getter(pname, int *out), out = "mov w8, #imm"
# of the case, false = not a fixed number. nvnDeviceGetInteger's switch is in its only caller: w0 is preset before the
# br (the API major version), a case is "mov w0, #imm", the preset itself (a case at the shared return), the getter's
# answer ("ldur w0, [x29, #-4]", 0 when the getter had none) or a field of the live device (-1 here).
def b_switch(br):
    """(bound, bias, table, base, preset w0) of an adr/ldrb jump table ending in the br at `br`, or None."""
    bias = bound = page = table = base = preset = None
    for va in range(br - 48, br, 4):
        w = sdk_ins(va)
        if (w & 0xffc00000) == 0x51000000: bias = (w >> 10) & 0xfff                          # sub wD, wN, #imm
        elif (w & 0xffc0001f) == 0x7100001f: bound = (w >> 10) & 0xfff                       # cmp wN, #imm
        elif (w & 0x9f000000) == 0x90000000:
            page = (va & ~0xfff) + (sx(((w >> 29) & 3) | (((w >> 5) & 0x7ffff) << 2), 21) << 12)
        elif (w & 0xffc00000) == 0x91000000 and page is not None: table = page + ((w >> 10) & 0xfff)
        elif (w & 0x9f000000) == 0x10000000: base = va + sx((((w >> 5) & 0x7ffff) << 2) | ((w >> 29) & 3), 21)
        elif mov_imm(w): preset = mov_imm(w)                                                   # (imm, register)
    if bound is None or table is None or base is None or not any((sdk_ins(br - k) & 0xffe0fc00) == 0x38606800 for k in range(4, 20, 4)):
        return None
    return bound, bias or 0, table, base, preset


def b_case(sw, p):
    bound, bias, table, base, _ = sw
    return base + 4 * sb[0x1000 + table + p - bias] if 0 <= p - bias <= bound else None


def find_b3_getint():
    text = sloads[0][2]
    for br in range(0, text, 4):
        if sdk_ins(br) & 0xfffffc1f != 0xd61f0000:
            continue
        sw = b_switch(br)
        if not sw or sw[0] < 0x40:
            continue
        cases = [b_case(sw, p) for p in (4, 0xf, 0x24, 0x25)]
        if all(c is not None and mov_imm(sdk_ins(c)) and mov_imm(sdk_ins(c))[0] == v
               for c, v in zip(cases, (256, 32, 1 << 20, 4096))):
            bls = {}                                     # the function's entry: the nearest BL target at or before the switch
            for va in range(0, text, 4):
                if sdk_ins(va) >> 26 == 0x25:
                    bls.setdefault(va + 4 * sx(sdk_ins(va) & 0x3ffffff, 26), []).append(va)
            fn = max(t for t in bls if br - 0x100 < t <= br)
            return sw, bls[fn]
    return None, []


